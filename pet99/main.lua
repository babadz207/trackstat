        updateToastStatus(_0x3KG_STR[43] .. tostring(PC_NAME) .. _0x3KG_STR[44], false)
    else
        updateToastStatus(_0x3KG_STR[122], false)
    end
    stats = nil
    jsonBody = nil
end
