    }
end
local function sendPs99Sync()
    local ok, stats = pcall(collectPs99Stats)
    if not ok or not stats then
        return
    end
    local jsonBody = nil
    pcall(function()
        jsonBody = HttpService:JSONEncode({ player = stats, gameId = tostring(game.PlaceId) })
    end)
    if not jsonBody then
        stats = nil
        return
    end
    local success, response = safeHttpRequest({
        Url = SERVER_URL .. _0x3KG_STR[185],
        Method = _0x3KG_STR[79],
        Headers = {
            [_0x3KG_STR[83]] = _0x3KG_STR[80],
            [_0x3KG_STR[84]] = API_KEY,
            [_0x3KG_STR[85]] = _0x3KG_STR[86] .. tostring(API_KEY)
        },
        Body = jsonBody
    })
    if success then
        updateToastStatus(_0x3KG_STR[109] .. tostring(PC_NAME) .. _0x3KG_STR[110], false)
    else
        updateToastStatus(_0x3KG_STR[186], false)
    end
    stats = nil
    jsonBody = nil
end
