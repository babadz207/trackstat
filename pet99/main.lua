    if data.Inventory then
        for categoryName, categoryData in pairs(data.Inventory) do
            if type(categoryData) == _0x3KG_STR[7] and categoryName ~= _0x3KG_STR[94] then
                local categoryItems = {}
                for uuid, item in pairs(categoryData) do
                    if type(item) == _0x3KG_STR[7] and item.id then
                        local id = tostring(item.id)
                        local amount = tonumber(item._am or item.Amount) or 1
                        local tier = item.tn or item.Tier
                        local iconUrl = GetItemIconData(id, categoryName, tier)
                        table.insert(categoryItems, {
                            UUID = tostring(uuid),
                            ID = id,
                            Tier = tier,
                            Amount = amount,
                            Category = categoryName,
                            IconUrl = iconUrl
                        })
                    end
                end
                categorizedItems[categoryName] = categoryItems
            end
        end
    end
    return {
        robloxId = tostring(LocalPlayer.UserId),
        username = LocalPlayer.Name,
