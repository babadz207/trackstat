        Url = SERVER_URL .. _0x3KG_STR[121],
        Method = _0x3KG_STR[12],
        Headers = {
            [_0x3KG_STR[17]] = _0x3KG_STR[13],
            [_0x3KG_STR[18]] = API_KEY,
            [_0x3KG_STR[19]] = _0x3KG_STR[20] .. tostring(API_KEY)
        },
        Body = jsonBody
