                ID = id,
                Type = typeName,
                Shiny = isShiny,
                Amount = amount,
                Equipped = isEquipped,
                IconUrl = petIcon
            }
            if isEquipped then
                table.insert(equippedPetsList, entry)
            end
            if string.find(lowerId, _0x3KG_STR[91]) then
                gargantuanCount = gargantuanCount + amount
                table.insert(ownedGargantuanList, entry)
            elseif string.find(lowerId, _0x3KG_STR[92]) then
                titanicCount = titanicCount + amount
                table.insert(ownedTitanicList, entry)
            elseif string.find(lowerId, _0x3KG_STR[93]) then
                hugeCount = hugeCount + amount
                table.insert(ownedHugeList, entry)
            end
        end
    end
