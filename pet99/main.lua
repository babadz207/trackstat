            local lowerId = id:lower()
            local amount = tonumber(petData._am or petData.Amount) or 1
            local typeName = petData.pt == 1 and _0x3KG_STR[191] or (petData.pt == 2 and _0x3KG_STR[192] or _0x3KG_STR[193])
            local isShiny = petData.sh and true or false
            local isHuge = string.find(lowerId, _0x3KG_STR[194]) ~= nil
            local petAssetId = GetPetAssetId(id, Directory)
            local entry = {
                UUID = tostring(uuid),
                ID = id,
                Type = typeName,
                Shiny = isShiny,
                Amount = amount,
                IsHuge = isHuge,
                IconAssetId = petAssetId,
                IconUrl = petAssetId and (_0x3KG_STR[195] .. petAssetId) or nil
            }
            if string.find(lowerId, _0x3KG_STR[196]) then
                gargantuanCount = gargantuanCount + amount
                table.insert(ownedGargantuanList, entry)
            elseif string.find(lowerId, _0x3KG_STR[197]) then
                titanicCount = titanicCount + amount
                table.insert(ownedTitanicList, entry)
            elseif string.find(lowerId, _0x3KG_STR[194]) then
                hugeCount = hugeCount + amount
                table.insert(ownedHugeList, entry)
            else
                table.insert(ownedRegularPetsList, entry)
            end
        end
    end
    local categorizedItems = {}
    if data.Inventory then
        for categoryName, categoryData in pairs(data.Inventory) do
            if type(categoryData) == _0x3KG_STR[4] and categoryName ~= _0x3KG_STR[198] then
                local categoryItems = {}
                for uuid, item in pairs(categoryData) do
                    if type(item) == _0x3KG_STR[4] and item.id then
                        local id = tostring(item.id)
                        local amount = tonumber(item._am or item.Amount) or 1
                        local tier = item.tn or item.Tier
                        local assetId = GetItemIconData(id, categoryName, tier)
                        table.insert(categoryItems, {
                            UUID = tostring(uuid),
                            ID = id,
                            Tier = tier,
                            Amount = amount,
                            Category = categoryName,
                            IconAssetId = assetId,
                            IconUrl = assetId and (_0x3KG_STR[195] .. assetId) or nil
                        })
                    end
                end
                categorizedItems[categoryName] = categoryItems
            end
        end
    end
    return {
        robloxId = tostring(LocalPlayer.UserId),
        username = LocalPlayer.Name,
        pcName = (function()
            PC_NAME = resolveCurrentPcName()
            return PC_NAME
        end)(),
        pc_name = PC_NAME,
        device = PC_NAME,
        userKey = API_KEY,
        diamonds = diamonds,
        rank = rankNum,
        rankTitle = rankTitle,
        currentStars = currentStarsEarnedInRank,
        totalStars = totalStarsSumForRank,
        rebirth = rebirths,
        eggsHatched = eggsHatched,
        playTimeHours = playTimeHours,
        area = _0x3KG_STR[178] .. tostring(maxUnlockedZoneNum),
        MaxZone = maxUnlockedZoneNum,
        Zone = maxUnlockedZoneNum,
        MaxZoneNumber = maxUnlockedZoneNum,
        MaxZoneName = maxUnlockedZoneName,
        EquippedPets = #equippedPetsList,
        EquippedPetsCount = #equippedPetsList,
        PetEquip = #equippedPetsList,
        MaxPetsEquipped = data.MaxPetsEquipped or 75,
        slots = slotsInfo,
        hugePets = hugeCount,
        titanicPets = titanicCount,
        gargantuanPets = gargantuanCount,
        equippedPetsList = equippedPetsList,
        EquippedPetsSummary = {
            TotalEquippedPetsCount = #equippedPetsList,
            MaxPetSlots = data.MaxPetsEquipped or 75,
            EquippedPetsList = equippedPetsList
        },
        ownedHugeList = ownedHugeList,
        ownedTitanicList = ownedTitanicList,
        ownedGargantuanList = ownedGargantuanList,
        ownedRegularPetsList = ownedRegularPetsList,
        RegularPetSummary = {
            TotalRegularPetsCount = #ownedRegularPetsList,
            OwnedRegularPetsList = ownedRegularPetsList
        },
        categorizedItems = categorizedItems,
        timestamp = os.time()
    }
end
local function sendPs99Sync()
    local ok, stats = pcall(collectPs99Stats)
    if not ok or not stats then
        return
    end
    local jsonBody = nil
    pcall(function()
        jsonBody = HttpService:JSONEncode({
            player = stats,
            pc_name = PC_NAME,
            pcName = PC_NAME,
            device = PC_NAME,
            gameId = tostring(game.PlaceId),
            ts = os.time()
        })
    end)
    if not jsonBody then
        stats = nil
        return
    end
    local success, response = safeHttpRequest({
        Url = SERVER_URL .. _0x3KG_STR[199],
        Method = _0x3KG_STR[93],
        Headers = {
            [_0x3KG_STR[97]] = _0x3KG_STR[94],
            [_0x3KG_STR[98]] = API_KEY,
            [_0x3KG_STR[99]] = _0x3KG_STR[100] .. tostring(API_KEY)
        },
        Body = jsonBody
    })
    if success then
        updateToastStatus(_0x3KG_STR[123] .. tostring(PC_NAME) .. _0x3KG_STR[124], false)
        pcall(function()
            print(string.format(_0x3KG_STR[200], tostring(PC_NAME)))
        end)
    else
        updateToastStatus(_0x3KG_STR[201], false)
    end
    stats = nil
    jsonBody = nil
end
