                            Amount = amount,
                            Category = categoryName,
                            IconAssetId = assetId,
                            IconUrl = assetId and (_0x3KG_STR[89] .. assetId) or nil
                        })
                    end
                end
                categorizedItems[categoryName] = categoryItems
            end
        end
    end
