                        local isHuge = string.find(string.lower(tostring(id)), _0x3KG_STR[194]) ~= nil
                        local petAssetId = GetPetAssetId(id, Directory)
                        table.insert(equippedPetsList, {
                            EquipSlotID = euid,
                            UUID = tostring(info.uid),
                            ID = id,
                            Type = typeName,
                            Shiny = isShiny,
                            IsHuge = isHuge,
                            IconAssetId = petAssetId,
