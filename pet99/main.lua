        end
    end)
    local rankNum = tonumber(data.Rank) or 1
    local rankTitle = RankTitleByNumber[rankNum] or (_0x3KG_STR[86] .. tostring(rankNum))
    local rebirths = tonumber(data.Rebirths) or 0
    local eggsHatched = tonumber(data.EggHatches or data.EggsHatched) or 0
    local playTimeHours = math.floor((tonumber(data.Age) or 0) / 3600)
    local maxUnlockedZoneNum = 1
    local maxUnlockedZoneName = _0x3KG_STR[87]
    pcall(function()
        if data and data.UnlockedZones and Directory and Directory.Zones then
            for zoneName, isUnlocked in pairs(data.UnlockedZones) do
                if isUnlocked then
                    local zObj = SafeGetDirectoryObj(Directory.Zones, zoneName)
                    if zObj then
                        local zNum = tonumber(zObj.ZoneNumber or zObj.Number or 0) or 0
                        if zNum > maxUnlockedZoneNum then
                            maxUnlockedZoneNum = zNum
                            maxUnlockedZoneName = tostring(zoneName)
                        end
                    elseif type(zoneName) == _0x3KG_STR[88] or tonumber(zoneName) then
                        local zNum = tonumber(zoneName)
                        if zNum > maxUnlockedZoneNum and zNum <= 300 then
                            maxUnlockedZoneNum = zNum
                        end
                    end
                end
            end
        end
        if maxUnlockedZoneNum == 1 and data and data.LastZoneBoughtEggs and Directory and Directory.Zones then
            local zObj = SafeGetDirectoryObj(Directory.Zones, data.LastZoneBoughtEggs)
            if zObj then
                maxUnlockedZoneNum = tonumber(zObj.ZoneNumber or zObj.Number or 279) or 279
                maxUnlockedZoneName = tostring(data.LastZoneBoughtEggs)
            end
        end
    end)
    local currentZone = _0x3KG_STR[89] .. tostring(maxUnlockedZoneNum)
    local starsEarned = 0
    pcall(function()
        if type(data.Stars) == _0x3KG_STR[88] then
            starsEarned = data.Stars
        elseif type(data.Stars) == _0x3KG_STR[7] then
            for _, v in pairs(data.Stars) do
                starsEarned = starsEarned + (tonumber(v) or 1)
            end
        elseif data.StarsEarned then
            starsEarned = tonumber(data.StarsEarned) or 0
        elseif data.RankStars then
            starsEarned = tonumber(data.RankStars) or 0
        elseif data.TotalStars then
            starsEarned = tonumber(data.TotalStars) or 0
        end
        if starsEarned == 0 and type(data.RedeemedRankRewards) == _0x3KG_STR[7] then
            for _, v in pairs(data.RedeemedRankRewards) do
                starsEarned = starsEarned + (tonumber(v) or 1)
            end
        end
        if starsEarned == 0 and type(data.Goals) == _0x3KG_STR[7] then
            for _, g in pairs(data.Goals) do
                if type(g) == _0x3KG_STR[7] and (g.Progress or g.Amount) then
                    starsEarned = starsEarned + (tonumber(g.Progress or g.Amount) or 0)
                end
            end
        end
    end)
    local totalStarsSumForRank = 0
    local rankObj = nil
    pcall(function()
        if Directory and Directory.Ranks then
            rankObj = Directory.Ranks[rankTitle]
        end
    end)
    if rankObj and rankObj.Rewards then
        for _, rewardItem in ipairs(rankObj.Rewards) do
            totalStarsSumForRank = totalStarsSumForRank + (tonumber(rewardItem.StarsRequired) or 0)
        end
    end
    if totalStarsSumForRank == 0 then
        totalStarsSumForRank = math.max(566, starsEarned)
    end
    local currentStarsEarnedInRank = starsEarned
    local slotsInfo = {
        MaxPetSlots = tonumber(data.MaxPetsEquipped) or 75,
        PetSlotsPurchased = tonumber(data.PetSlotsPurchased) or 71,
        MaxEggHatchSlots = 15 + (tonumber(data.EggSlotsPurchased) or 70),
        EggSlotsPurchased = tonumber(data.EggSlotsPurchased) or 70,
        MaxEnchantSlots = tonumber(data.MaxEnchantsEquipped) or 5,
        EquippedUltimate = tostring(data.EquippedUltimateId or _0x3KG_STR[90])
    }
    local ownedHugeList = {}
    local ownedTitanicList = {}
    local ownedGargantuanList = {}
    local equippedPetsList = {}
    local hugeCount = 0
    local titanicCount = 0
    local gargantuanCount = 0
    local function SafeGetDirectoryObj(dirTable, id)
        local obj = nil
        pcall(function()
            if dirTable and dirTable[id] ~= nil then
                obj = dirTable[id]
            end
        end)
        return obj
    end
    local function GetItemIconData(id, rawCategory, tier)
        local obj = nil
        pcall(function()
            if Directory then
                if rawCategory == _0x3KG_STR[91] then obj = SafeGetDirectoryObj(Directory.Enchants, id)
                elseif rawCategory == _0x3KG_STR[92] then obj = SafeGetDirectoryObj(Directory.Potions, id)
                elseif rawCategory == _0x3KG_STR[93] then obj = SafeGetDirectoryObj(Directory.Fruits, id)
                elseif rawCategory == _0x3KG_STR[94] then obj = SafeGetDirectoryObj(Directory.Currency, id)
                elseif rawCategory == _0x3KG_STR[95] then obj = SafeGetDirectoryObj(Directory.Consumables, id)
                elseif rawCategory == _0x3KG_STR[96] then obj = SafeGetDirectoryObj(Directory.CardItems, id)
                elseif rawCategory == _0x3KG_STR[97] then obj = SafeGetDirectoryObj(Directory.Charms, id)
                elseif rawCategory == _0x3KG_STR[98] or rawCategory == _0x3KG_STR[99] then obj = SafeGetDirectoryObj(Directory.Lootboxes, id) or SafeGetDirectoryObj(Directory.Boxes, id)
                elseif rawCategory == _0x3KG_STR[100] then obj = SafeGetDirectoryObj(Directory.MiscItems, id)
                end
                if not obj then
                    obj = SafeGetDirectoryObj(Directory.Consumables, id) or SafeGetDirectoryObj(Directory.MiscItems, id) or SafeGetDirectoryObj(Directory.Enchants, id) or SafeGetDirectoryObj(Directory.Potions, id)
                end
            end
        end)
        if not obj then return nil end
        local icon = obj.Icon or obj.Image or obj.IconId or obj.Thumbnail or obj.Texture
        if type(icon) == _0x3KG_STR[16] then
            pcall(function()
                icon = icon(tier or 1)
            end)
        end
        if type(icon) == _0x3KG_STR[101] or type(icon) == _0x3KG_STR[88] then
            local str = tostring(icon)
            local assetId = string.match(str, _0x3KG_STR[19])
            if assetId then
                return assetId
            end
        end
        return nil
    end
    local equippedPetsList = {}
    local ownedRegularPetsList = {}
    pcall(function()
        local PetCmds = require(ReplicatedStorage.Library.Client.PetCmds)
        if PetCmds and PetCmds.GetEquipped then
            local equippedMap = PetCmds.GetEquipped()
            if equippedMap then
                for euid, info in pairs(equippedMap) do
                    if type(info) == _0x3KG_STR[7] and info.uid then
                        local petData = data and data.Inventory and data.Inventory.Pet and data.Inventory.Pet[info.uid]
                        local id = petData and petData.id or _0x3KG_STR[6]
                        local typeName = petData and (petData.pt == 1 and _0x3KG_STR[102] or (petData.pt == 2 and _0x3KG_STR[103] or _0x3KG_STR[104])) or _0x3KG_STR[104]
                        local isShiny = petData and (petData.sh and true or false) or false
                        local isHuge = string.find(string.lower(tostring(id)), _0x3KG_STR[105]) ~= nil
                        local petAssetId = GetPetAssetId(id, Directory)
                        table.insert(equippedPetsList, {
                            EquipSlotID = euid,
                            UUID = tostring(info.uid),
                            ID = id,
                            Type = typeName,
                            Shiny = isShiny,
                            IsHuge = isHuge,
                            IconAssetId = petAssetId,
                            IconUrl = petAssetId and (_0x3KG_STR[106] .. petAssetId) or nil
                        })
                    end
                end
            end
        end
    end)
    if data.Inventory and data.Inventory.Pet then
        for uuid, petData in pairs(data.Inventory.Pet) do
            local id = tostring(petData.id or _0x3KG_STR[6])
            local lowerId = id:lower()
            local amount = tonumber(petData._am or petData.Amount) or 1
            local typeName = petData.pt == 1 and _0x3KG_STR[102] or (petData.pt == 2 and _0x3KG_STR[103] or _0x3KG_STR[104])
            local isShiny = petData.sh and true or false
            local isHuge = string.find(lowerId, _0x3KG_STR[105]) ~= nil
            local petAssetId = GetPetAssetId(id, Directory)
            local entry = {
                UUID = tostring(uuid),
                ID = id,
                Type = typeName,
                Shiny = isShiny,
                Amount = amount,
                IsHuge = isHuge,
                IconAssetId = petAssetId,
                IconUrl = petAssetId and (_0x3KG_STR[106] .. petAssetId) or nil
            }
            if string.find(lowerId, _0x3KG_STR[107]) then
                gargantuanCount = gargantuanCount + amount
                table.insert(ownedGargantuanList, entry)
            elseif string.find(lowerId, _0x3KG_STR[108]) then
                titanicCount = titanicCount + amount
                table.insert(ownedTitanicList, entry)
            elseif string.find(lowerId, _0x3KG_STR[105]) then
                hugeCount = hugeCount + amount
                table.insert(ownedHugeList, entry)
            else
                table.insert(ownedRegularPetsList, entry)
            end
        end
    end
    local categorizedItems = {}
    if data.Inventory then
        for categoryName, categoryData in pairs(data.Inventory) do
            if type(categoryData) == _0x3KG_STR[7] and categoryName ~= _0x3KG_STR[109] then
                local categoryItems = {}
                for uuid, item in pairs(categoryData) do
                    if type(item) == _0x3KG_STR[7] and item.id then
                        local id = tostring(item.id)
                        local amount = tonumber(item._am or item.Amount) or 1
                        local tier = item.tn or item.Tier
                        local assetId = GetItemIconData(id, categoryName, tier)
                        table.insert(categoryItems, {
                            UUID = tostring(uuid),
                            ID = id,
                            Tier = tier,
                            Amount = amount,
                            Category = categoryName,
                            IconAssetId = assetId,
                            IconUrl = assetId and (_0x3KG_STR[106] .. assetId) or nil
                        })
                    end
                end
                categorizedItems[categoryName] = categoryItems
            end
        end
    end
    return {
        robloxId = tostring(LocalPlayer.UserId),
        username = LocalPlayer.Name,
        displayName = LocalPlayer.DisplayName,
        pcName = PC_NAME,
        userKey = API_KEY,
        diamonds = diamonds,
        rank = rankNum,
        rankTitle = rankTitle,
        currentStars = currentStarsEarnedInRank,
        totalStars = totalStarsSumForRank,
        rebirth = rebirths,
        eggsHatched = eggsHatched,
        playTimeHours = playTimeHours,
        area = _0x3KG_STR[89] .. tostring(maxUnlockedZoneNum),
        MaxZone = maxUnlockedZoneNum,
        Zone = maxUnlockedZoneNum,
        MaxZoneNumber = maxUnlockedZoneNum,
        MaxZoneName = maxUnlockedZoneName,
        EquippedPets = #equippedPetsList,
        EquippedPetsCount = #equippedPetsList,
        PetEquip = #equippedPetsList,
        MaxPetsEquipped = data.MaxPetsEquipped or 75,
        slots = slotsInfo,
        hugePets = hugeCount,
        titanicPets = titanicCount,
        gargantuanPets = gargantuanCount,
        equippedPetsList = equippedPetsList,
        EquippedPetsSummary = {
            TotalEquippedPetsCount = #equippedPetsList,
            MaxPetSlots = data.MaxPetsEquipped or 75,
            EquippedPetsList = equippedPetsList
        },
        ownedHugeList = ownedHugeList,
        ownedTitanicList = ownedTitanicList,
        ownedGargantuanList = ownedGargantuanList,
        ownedRegularPetsList = ownedRegularPetsList,
        RegularPetSummary = {
            TotalRegularPetsCount = #ownedRegularPetsList,
            OwnedRegularPetsList = ownedRegularPetsList
        },
        categorizedItems = categorizedItems,
        timestamp = os.time()
    }
end
