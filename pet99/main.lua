local function sendPs99Sync()
    local ok, stats = pcall(collectPs99Stats)
    if not ok or not stats then
        return
    end
    local jsonBody = nil
    pcall(function()
        jsonBody = HttpService:JSONEncode({ player = stats, gameId = tostring(game.PlaceId) })
    end)
    if not jsonBody then
        stats = nil
        return
    end
    local success, response = safeHttpRequest({
        Url = SERVER_URL .. _0x3KG_STR[149],
        Method = _0x3KG_STR[43],
        Headers = {
            [_0x3KG_STR[47]] = _0x3KG_STR[44],
            [_0x3KG_STR[48]] = API_KEY,
            [_0x3KG_STR[49]] = _0x3KG_STR[50] .. tostring(API_KEY)
        },
        Body = jsonBody
    })
    if success then
        updateToastStatus(_0x3KG_STR[73] .. tostring(PC_NAME) .. _0x3KG_STR[74], false)
    else
        updateToastStatus(_0x3KG_STR[150], false)
    end
    stats = nil
    jsonBody = nil
end
updateToastStatus(_0x3KG_STR[73] .. tostring(PC_NAME) .. _0x3KG_STR[74], false)
task.spawn(function()
    pcall(sendPs99Sync)
end)
task.spawn(function()
    while true do
        task.wait(15)
        pcall(sendPs99Sync)
    end
end)