        pcall(function()
            SaveMod = require(ReplicatedStorage.Shared.Save)
            EggRecords = require(ReplicatedStorage.Shared.Util.EggRecords)
            AssetsData = require(ReplicatedStorage.Data.Assets)
        end)
    end
