                    alpha = math.clamp(EggRecords.GrowthAlpha(decoded, now, 1), 0, 1)
                end)
            else
                remaining = math.floor(duration)
                alpha = 0
            end
            local isReady = isPlaced and (remaining <= 0)
            local mutList = decoded.Mutations or {}
            local mult = GetMutationMultiplier(mutList)
