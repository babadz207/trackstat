                updateToastStatus(_0x3KG_STR[71], false)
                warn(_0x3KG_STR[72] .. tostring(data.message or data.error))
            end
        else
            updateToastStatus(_0x3KG_STR[71], false)
        end
    else
        updateToastStatus(_0x3KG_STR[71], false)
    end
    isSyncing = false
end
