local function FormatTime(seconds)
    if not seconds or seconds <= 0 then return _0x3KG_STR[52] end
    local h = math.floor(seconds / 3600)
    local m = math.floor((seconds % 3600) / 60)
    local s = math.floor(seconds % 60)
    return string.format(_0x3KG_STR[53], h, m, s)
end
local function GetMutationMultiplier(mutations)
    if not mutations or #mutations == 0 then return 1 end
    if MutationsMod and type(MutationsMod.EarningsFor) == _0x3KG_STR[7] then
        local ok, mult = pcall(function()
            return MutationsMod.EarningsFor(mutations, 1)
        end)
        if ok and type(mult) == _0x3KG_STR[54] then return mult end
    end
    local mult = 1
    for _, mut in ipairs(mutations) do
        if mut == _0x3KG_STR[55] then mult = mult * 1.2
        elseif mut == _0x3KG_STR[56] then mult = mult * 2.5
        elseif mut == _0x3KG_STR[57] then mult = mult * 3.5
        end
    end
    return mult
end
