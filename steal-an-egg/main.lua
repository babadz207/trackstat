        return
    end
    local payload
    local encOk, encRes = pcall(function() return HttpService:JSONEncode(stats) end)
    if encOk then
        payload = encRes
    else
        isSyncing = false
        return
    end
    local reqOk, res = safeHttpRequest({
        Url = SERVER_URL .. _0x3KG_STR[68],
        Method = _0x3KG_STR[19],
        Headers = {
            [_0x3KG_STR[24]] = _0x3KG_STR[20],
            [_0x3KG_STR[25]] = userKey,
            [_0x3KG_STR[26]] = _0x3KG_STR[27] .. tostring(userKey)
        },
        Body = payload
    })
    if reqOk and res and res.Body then
        local decOk, data = pcall(function() return HttpService:JSONDecode(res.Body) end)
        if decOk and data then
            if data.success then
                updateToastStatus(_0x3KG_STR[49] .. tostring(PC_NAME) .. _0x3KG_STR[50], false)
                print(string.format(_0x3KG_STR[69],
                    stats.username, tostring(stats.speed), tostring(stats.moneyPerSecond), stats.eggCount, stats.equippedCount))
            elseif data.error == _0x3KG_STR[70] then
                updateToastStatus(_0x3KG_STR[71], true)
                warn(_0x3KG_STR[72] .. tostring(data.message))
            else
                updateToastStatus(_0x3KG_STR[73], false)
                warn(_0x3KG_STR[74] .. tostring(data.message or data.error))
            end
        else
            updateToastStatus(_0x3KG_STR[73], false)
        end
    else
        updateToastStatus(_0x3KG_STR[73], false)
    end
    isSyncing = false
end
