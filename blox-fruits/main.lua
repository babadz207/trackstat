local lastStatHash = ""
local lastSyncTime = 0
local function computeStatHash(stats)
    local invHash = 0
    if type(stats.inventory) == _0x3KG_STR[4] then
        invHash = #stats.inventory
        for _, it in ipairs(stats.inventory) do
            invHash = invHash + (it.count or 1) + (it.mastery or 0)
        end
    end
    return tostring(stats.level) .. _0x3KG_STR[493] .. tostring(stats.bounty) .. _0x3KG_STR[493] .. tostring(stats.beli) .. _0x3KG_STR[493] .. tostring(stats.fragments) .. _0x3KG_STR[493] .. tostring(stats.fruit) .. _0x3KG_STR[493] .. tostring(stats.race) .. _0x3KG_STR[493] .. tostring(stats.fightingStyle) .. _0x3KG_STR[493] .. tostring(stats.currentSword) .. _0x3KG_STR[493] .. tostring(invHash)
end
local lastHttpPingMs = 35
local function sendSync(force)
    if not LocalPlayer or not LocalPlayer.Team or LocalPlayer.Team.Name == "" or LocalPlayer.Team.Name == _0x3KG_STR[66] then
        updateToastStatus(_0x3KG_STR[494], false)
        return
    end
    local ok, stats = pcall(collectStats)
    if not ok or not stats then
        updateToastStatus(_0x3KG_STR[495], false)
        return
    end
    stats.ping = lastHttpPingMs or 35
    local currentHash = computeStatHash(stats)
    local now = os.time()
    if not force and currentHash == lastStatHash and (now - lastSyncTime < 30) then
        updateToastStatus(_0x3KG_STR[496] .. tostring(PC_NAME) .. _0x3KG_STR[60], false)
        return
    end
    local reqStart = tick()
    local success, response = safeHttpRequest({
        Url = SERVER_URL .. _0x3KG_STR[497],
        Method = _0x3KG_STR[29],
        Headers = {
            [_0x3KG_STR[34]] = _0x3KG_STR[30],
            [_0x3KG_STR[35]] = API_KEY,
            [_0x3KG_STR[36]] = _0x3KG_STR[37] .. tostring(API_KEY)
        },
        Body = HttpService:JSONEncode({ player = stats, gameId = tostring(game.PlaceId), ts = os.time() })
    })
    if success and response and (response.StatusCode == 200 or response.StatusCode == 201) then
        local reqDuration = math.floor((tick() - reqStart) * 1000)
        if reqDuration > 0 and reqDuration < 10000 then
            lastHttpPingMs = reqDuration
        end
        lastStatHash = currentHash
        lastSyncTime = now
        updateToastStatus(_0x3KG_STR[496] .. tostring(PC_NAME) .. _0x3KG_STR[60], false)
    else
        updateToastStatus(_0x3KG_STR[498], false)
    end
end
