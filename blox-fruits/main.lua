            [_0x3KG_STR[18]] = API_KEY
        },
        Body = HttpService:JSONEncode({ player = stats, gameId = tostring(game.PlaceId) })
    })
    if success and response and (response.StatusCode == 200 or response.StatusCode == 201) then
        lastStatHash = currentHash
        lastSyncTime = now
